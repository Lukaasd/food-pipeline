USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS FOOD_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;


-- Database + medallion schemas.

CREATE DATABASE IF NOT EXISTS FOOD;
CREATE SCHEMA IF NOT EXISTS FOOD.BRONZE;
CREATE SCHEMA IF NOT EXISTS FOOD.RAW;
CREATE SCHEMA IF NOT EXISTS FOOD.STAGING;
CREATE SCHEMA IF NOT EXISTS FOOD.MARTS;
CREATE SCHEMA IF NOT EXISTS FOOD.SNAPSHOTS;
CREATE SCHEMA IF NOT EXISTS FOOD.AI;


-- A role dbt/airflow will use.

CREATE ROLE IF NOT EXISTS DBT_ROLE;
GRANT USAGE ON WAREHOUSE FOOD_WH TO ROLE DBT_ROLE;
GRANT OPERATE ON WAREHOUSE FOOD_WH TO ROLE DBT_ROLE;
GRANT ALL ON DATABASE FOOD TO ROLE DBT_ROLE;
GRANT ALL ON ALL SCHEMAS IN DATABASE FOOD TO ROLE DBT_ROLE;
GRANT ALL ON FUTURE SCHEMAS IN DATABASE FOOD TO ROLE DBT_ROLE;
GRANT ALL ON FUTURE TABLES IN DATABASE FOOD TO ROLE DBT_ROLE;
GRANT ALL ON FUTURE VIEWS IN DATABASE FOOD TO ROLE DBT_ROLE;


SET my_user = '"' || CURRENT_USER() || '"';

GRANT ROLE DBT_ROLE TO USER IDENTIFIER($my_user);

SELECT 'setup complete' AS status;


SELECT CURRENT_USER() AS usuario, CURRENT_ROLE() AS rol_activo;