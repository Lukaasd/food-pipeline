USE ROLE ACCOUNTADMIN;
USE DATABASE FOOD;
USE SCHEMA RAW;

CREATE OR REPLACE FILE FORMAT FOOD.RAW.CSV_FMT
    TYPE = 'CSV'
    COMPRESSION = 'AUTO'
    FIELD_DELIMITER = ','
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    SKIP_HEADER = 1
    EMPTY_FIELD_AS_NULL = TRUE
    NULL_IF = (' ', '\N', 'NULL')
    TRIM_SPACE = FALSE
    ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE;



USE ROLE ACCOUNTADMIN;

CREATE OR REPLACE STAGE FOOD.RAW.FOOD_RAW_STAGE
  URL = 's3://REEMPLAZAR_BUCKET/raw/'
  CREDENTIALS = (
    AWS_KEY_ID = 'REEMPLAZAR_AWS_KEY_ID'
    AWS_SECRET_KEY = 'REEMPLAZAR_AWS_SECRET_KEY'
  )
  FILE_FORMAT = (
    FORMAT_NAME = 'FOOD.RAW.CSV_FMT'
  );

GRANT USAGE ON STAGE FOOD.RAW.FOOD_RAW_STAGE
  TO ROLE DBT_ROLE;

GRANT USAGE ON FILE FORMAT FOOD.RAW.CSV_FMT
  TO ROLE DBT_ROLE;

LIST @FOOD.RAW.FOOD_RAW_STAGE;
